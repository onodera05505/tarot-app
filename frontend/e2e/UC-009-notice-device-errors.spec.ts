import { test, expect } from '@playwright/test'

// UC-009 端末で起きたエラーを知る（docs/goals/GOAL-07-release-awareness/UC-009-notice-device-errors/UC.md）
// 主シナリオの 4 手順のうち、ブラウザから観測できるのは 2（エラーが起きたこととトップへ戻る手段の表示）だけ。
// 1（描画中に予期しないエラーが起きる）は外から起こす手段が UC にも契約にも無く、
// 3（エラー監視サービスへの報告）はプレビューの版に報告先（ビルド時の値。CI が正本）が渡っているかを
// このテストの環境が決めておらず、4（運営者が報告を見る）はエラー監視サービス側の画面で、ブラウザの外。
// 起こせない手順は本文に書かず、報告の (d) に残す。
// ロケータは用語集の語から導く: 「トップへ戻る」（docs/01-glossary.md、操作）。
test.describe('UC-009', { tag: ['@UC-009'] }, () => {
  // 保留の理由: 手順 1 を外から起こす手段が決まっておらず、実ブラウザでの確認も未了
  // @scenario UC-009
  test.fixme('UC-009: 端末で起きたエラーを知る', async ({ page }) => {
    // 手順 1: 画面の描画中に予期しないエラーが起きる —— 外から起こす手段が無いため、ここでは起こせない。
    // アプリを開くところまでが、いまブラウザから起こせる手順。
    await page.goto('/')

    // 手順 2: システムが占う人に、エラーが起きたことと、トップへ戻る手段を示す（用語集「エラーの表示中」「トップへ戻る」）
    await expect(page.getByRole('button', { name: 'トップへ戻る' })).toBeVisible()

    // 手順 3・4 と成功時の事後条件（運営者がエラー監視サービスで報告を見ている）はブラウザの外（報告の (d)）。
  })
})
