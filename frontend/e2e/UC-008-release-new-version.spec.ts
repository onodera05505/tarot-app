import { test, expect } from '@playwright/test'

// UC-008 新しい版を配って端末に届いたことを確かめる（docs/goals/GOAL-07-release-awareness/UC-008-release-new-version/UC.md）
// 主シナリオの 6 手順のうち、ブラウザから起こせて観測できるのは 3（アプリを開く）・5（トップを開く）・6（ビルド識別子を見る）だけ。
// 1（版を出す）・2（検査の 4 段を通して配る）は配る手順（CI）の層、4（配信元への問い合わせと自動更新）は
// プレビューサーバーに新旧 2 つの版が無いので起こせない。起こせない手順は本文に書かず、報告の (d) に残す。
// ロケータは用語集の語から導く: 「ビルド識別子」（docs/01-glossary.md）をアクセシブルな名前に持つ要素。
test.describe('UC-008', { tag: ['@UC-008'] }, () => {
  // 保留の理由: 実装の配線と実ブラウザでの確認が未了（ビルド識別子の要素に用語集の語が付いていることも未確認）
  // @scenario UC-008
  test.fixme('UC-008: 新しい版を配って端末に届いたことを確かめる', async ({ page }) => {
    // 手順 3: 運営者が端末でアプリを開く（手順 5 のトップは `/`。用語集「トップ」）
    await page.goto('/')

    // 手順 6 / 成功時の事後条件: トップに稼働中の版のビルド識別子が示され、運営者がそれを見ている
    const buildId = page.getByLabel('ビルド識別子')
    await expect(buildId).toBeVisible()
    await expect(buildId).toHaveText(/\S/)
    // 「出した版の」識別子と一致することは、手順 1・2 を担う配る手順（CI）が識別子をこの実行に渡さない限り
    // ブラウザからは照合できない（報告の (d)）。ここでは示されていることまでを観測する。
  })
})
